import { db } from '@/lib/db';
import { ok, fail, toAppError } from '@/lib/api/envelope';
import { withRateLimit } from '@/lib/api/with-auth';
import { ValidationError } from '@platform/core/errors';
import {
  haversineKm,
  formatDistance,
  isValidCoordinate,
  boundingBox,
  isInsideBoundingBox,
} from '@/lib/location/distance';
import { shopOpenStatus } from '@/lib/location/opening-hours';

/**
 * GET /api/shops/nearby — public location-aware shop discovery.
 *
 * Query params:
 *   - lat, lng: customer coordinates (decimal degrees). Both or neither;
 *     one without the other is a 400. When absent the endpoint runs in
 *     search mode (text search only, no distances).
 *   - radius: one of 1 | 3 | 5 | 10 | 25 km (default 10). Only applies
 *     when lat/lng are given; anything else is a 400.
 *   - search: free text, matches name / address / city (case-insensitive).
 *   - openNow: "true" — only shops open right now (schedule + manual flags).
 *   - service: only shops listing this service in servicesJson
 *     (e.g. bw_print, color_print, scan, laminate, binding).
 *   - sort: "nearest" (default with lat/lng) | "name" (default without).
 *   - page: 1-based (default 1). limit: page size (default 20, max 50).
 *
 * No PostGIS: the DB query filters active shops (+ text search) and the
 * bounding-box prefilter, exact Haversine distance, radius cut and sort
 * all happen in JS. The fetch is capped (FETCH_CAP) — see note below.
 *
 * Response: only public fields. rating is always null and reviewCount
 * always 0 — there is no ratings/reviews table, so nothing is invented.
 * Shops without coordinates are included in BOTH modes, with distanceKm
 * null and no fabricated distance — they sort after located shops in
 * nearest mode. Excluding them in location mode used to empty the whole
 * list after a successful location detect (no shop has coordinates yet),
 * which read on the phone as "location detection doesn't work".
 * `locatedCount` tells the client how many results actually have a map
 * location, so the page can say so plainly instead of going blank.
 * Phone is masked exactly like GET /api/v1/shops (first 4 + last 4 digits).
 */

const ALLOWED_RADII = [1, 3, 5, 10, 25] as const;
/** Max rows pulled from the DB before the in-JS geo filter runs. */
const FETCH_CAP = 500;

/** Raw Prisma Shop row, restricted to the columns this endpoint reads. */
interface ShopLocationRow {
  id: string;
  name: string;
  slug: string;
  address: string;
  phone: string;
  timezone: string | null;
  isActive: boolean;
  isOpen: boolean | null;
  acceptingOrders: boolean | null;
  openingHours: unknown;
  logoUrl: string | null;
  servicesJson: string | null;
  pricingConfig: string | null;
  latitude: number | null;
  longitude: number | null;
  fullAddress: string | null;
  city: string | null;
  minutesPerPageBw: number | null;
  minutesPerPageColor: number | null;
}

// The generated Prisma client in node_modules predates the location columns
// (it is regenerated by `prisma generate` in scripts/vercel-build.sh), so
// the new fields are not on its generated Shop type yet. This narrow cast
// keeps the query typed against the actual columns without touching the
// generated client. The select list below is the contract — keep it in sync
// with prisma/schema.prisma.
const shopDelegate = (
  db as unknown as {
    shop: { findMany: (args: unknown) => Promise<ShopLocationRow[]> };
  }
).shop;

/** Same masking as GET /api/v1/shops: first 4 + last 4 digits only. */
function maskPhone(phone: string | null | undefined): string {
  if (!phone) return '';
  const digits = phone.replace(/\D/g, '');
  if (digits.length === 0) return '';
  if (digits.length < 8) {
    return '*'.repeat(digits.length - 2) + digits.slice(-2);
  }
  return `${digits.slice(0, 4)}${'*'.repeat(digits.length - 8)}${digits.slice(-4)}`;
}

function parseServices(servicesJson: string | null): string[] {
  if (!servicesJson) return [];
  try {
    const parsed: unknown = JSON.parse(servicesJson);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((s): s is string => typeof s === 'string');
  } catch {
    return [];
  }
}

interface PricingSummary {
  bwA4PerPage: number;
  colorA4PerPage: number;
  minOrderValue: number;
}

function parsePricing(pricingConfig: string | null): PricingSummary {
  // Same defaults as GET /api/v1/shops (paise per page).
  const fallback = { bwA4PerPage: 200, colorA4PerPage: 500, minOrderValue: 1000 };
  if (!pricingConfig) return fallback;
  try {
    const p = JSON.parse(pricingConfig) as Partial<{
      bw_a4_per_page: number;
      color_a4_per_page: number;
      min_order_value: number;
    }>;
    return {
      bwA4PerPage: p.bw_a4_per_page ?? fallback.bwA4PerPage,
      colorA4PerPage: p.color_a4_per_page ?? fallback.colorA4PerPage,
      minOrderValue: p.min_order_value ?? fallback.minOrderValue,
    };
  } catch {
    return fallback;
  }
}

function parseBoolParam(
  raw: string | null,
  name: string,
): boolean | undefined {
  if (raw === null) return undefined;
  const v = raw.trim().toLowerCase();
  if (v === 'true' || v === '1') return true;
  if (v === 'false' || v === '0') return false;
  throw new ValidationError(`${name} must be "true" or "false"`);
}

export const GET = withRateLimit('shops-nearby', 300, 60, async (req) => {
  try {
    const params = req.nextUrl.searchParams;

    // ── Validate coordinates ──────────────────────────────────────────
    const latRaw = params.get('lat');
    const lngRaw = params.get('lng');
    const hasCoords = latRaw !== null || lngRaw !== null;
    let lat: number | null = null;
    let lng: number | null = null;
    if (hasCoords) {
      if (latRaw === null || lngRaw === null) {
        throw new ValidationError('lat and lng must be provided together');
      }
      lat = Number(latRaw);
      lng = Number(lngRaw);
      if (!isValidCoordinate(lat, lng)) {
        throw new ValidationError(
          'lat must be between -90 and 90 and lng between -180 and 180',
        );
      }
    }

    // ── Validate radius (allowed set only) ────────────────────────────
    const radiusRaw = params.get('radius');
    let radiusKm = 10;
    if (radiusRaw !== null) {
      const r = Number(radiusRaw);
      if (!Number.isInteger(r) || !(ALLOWED_RADII as readonly number[]).includes(r)) {
        throw new ValidationError(
          `radius must be one of ${ALLOWED_RADII.join(', ')}`,
        );
      }
      radiusKm = r;
    }

    const search = (params.get('search') ?? '').trim();
    const openNow = parseBoolParam(params.get('openNow'), 'openNow') ?? false;
    const service = (params.get('service') ?? '').trim() || null;
    // Default sort is "nearest" when coordinates are given, "name" in
    // search mode (no coordinates) — "nearest" without lat/lng is
    // meaningless, so fall back instead of 400ing a plain text search.
    const sortParam = params.get('sort')?.trim().toLowerCase();
    const sort = sortParam ?? (hasCoords ? 'nearest' : 'name');
    if (sort !== 'nearest' && sort !== 'name') {
      throw new ValidationError('sort must be "nearest" or "name"');
    }
    if (sort === 'nearest' && !hasCoords) {
      throw new ValidationError('sort=nearest requires lat and lng');
    }
    const page = Math.max(parseInt(params.get('page') ?? '1', 10) || 1, 1);
    const limit = Math.min(
      Math.max(parseInt(params.get('limit') ?? '20', 10) || 20, 1),
      50,
    );

    // ── DB fetch: active shops (+ text search at the DB layer) ───────
    // No PostGIS, so geo filtering happens below in JS. The text search
    // runs in Postgres so the fetch stays small for typed queries.
    const where: Record<string, unknown> = { isActive: true };
    if (search) {
      const contains = { contains: search, mode: 'insensitive' };
      where.OR = [
        { name: contains },
        { address: contains },
        { fullAddress: contains },
        { city: contains },
      ];
    }
    const rows = await shopDelegate.findMany({
      where,
      select: {
        id: true,
        name: true,
        slug: true,
        address: true,
        phone: true,
        timezone: true,
        isActive: true,
        isOpen: true,
        acceptingOrders: true,
        openingHours: true,
        logoUrl: true,
        servicesJson: true,
        pricingConfig: true,
        latitude: true,
        longitude: true,
        fullAddress: true,
        city: true,
        minutesPerPageBw: true,
        minutesPerPageColor: true,
      },
      orderBy: { createdAt: 'desc' },
      take: FETCH_CAP,
    });
    const truncated = rows.length === FETCH_CAP;

    const now = new Date();
    const box =
      hasCoords && lat !== null && lng !== null
        ? boundingBox(lat, lng, radiusKm)
        : null;

    // ── In-JS geo + status + service filtering ────────────────────────
    const enriched = rows
      .map((s) => {
        const hasShopCoords =
          s.latitude !== null &&
          s.longitude !== null &&
          isValidCoordinate(s.latitude, s.longitude);
        let distanceKm: number | null = null;
        if (hasCoords && hasShopCoords && lat !== null && lng !== null) {
          distanceKm = haversineKm(
            { latitude: lat, longitude: lng },
            { latitude: s.latitude as number, longitude: s.longitude as number },
          );
        }
        const status = shopOpenStatus(
          {
            openingHours: s.openingHours,
            timezone: s.timezone,
            isOpen: s.isOpen,
            acceptingOrders: s.acceptingOrders,
          },
          now,
        );
        return { row: s, hasShopCoords, distanceKm, status };
      })
      .filter(({ row, hasShopCoords, distanceKm }) => {
        // Shops without coordinates are NOT excluded when the customer
        // gave a location: they sort last with distanceKm null (see sort
        // below). Dropping them emptied the list entirely while no shop
        // has coordinates yet — the "location doesn't work" report.
        if (hasCoords && box && hasShopCoords) {
          if (
            !isInsideBoundingBox(
              {
                latitude: row.latitude as number,
                longitude: row.longitude as number,
              },
              box,
            )
          ) {
            return false;
          }
        }
        // Exact Haversine cut (the box is only a prefilter).
        if (hasCoords && distanceKm !== null && distanceKm > radiusKm) {
          return false;
        }
        return true;
      })
      .filter(({ status }) => !openNow || status.open)
      .filter(({ row }) => {
        if (!service) return true;
        return parseServices(row.servicesJson).includes(service);
      });

    // ── Sort ──────────────────────────────────────────────────────────
    if (sort === 'nearest') {
      enriched.sort((a, b) => {
        const da = a.distanceKm ?? Number.POSITIVE_INFINITY;
        const db = b.distanceKm ?? Number.POSITIVE_INFINITY;
        return da - db;
      });
    } else {
      enriched.sort((a, b) => a.row.name.localeCompare(b.row.name));
    }

    // ── Paginate (in memory — the geo filter already ran) ─────────────
    const total = enriched.length;
    const locatedCount = enriched.filter((e) => e.hasShopCoords).length;
    const totalPages = Math.max(1, Math.ceil(total / limit));
    const pageRows = enriched.slice((page - 1) * limit, page * limit);

    // ── Live queue per shop on this page ──────────────────────────────
    // The customer-facing "Queue: N waiting · Ready in ~M mins" line.
    // Same formula as the public shops list (/api/v1/shops): queued
    // sheets × minutes-per-page ÷ online printers, ceil. Best-effort —
    // any failure leaves the fields null and the card falls back to the
    // plain Open/Closed chip.
    const queueByShop = new Map<string, { queueCount: number; waitMinutes: number | null }>();
    await Promise.all(
      pageRows.map(async ({ row }) => {
        try {
          const printers = await db.printer.findMany({ where: { shopId: row.id } });
          const online = printers.filter((p) => p.enabled && p.status === 'ONLINE');
          const queued = await db.printJob.findMany({
            where: { shopId: row.id, status: 'queued' },
            take: 50,
          });
          const waiting = queued.length;
          if (online.length === 0) {
            queueByShop.set(row.id, { queueCount: waiting, waitMinutes: null });
            return;
          }
          const minBw = row.minutesPerPageBw ?? 1;
          const minColor = row.minutesPerPageColor ?? 2;
          const minPerPp = Math.max(1, Math.round((minBw + minColor) / 2));
          const sheets = queued.reduce(
            (sum, t) => sum + (t.sheetCount ?? 1) * (t.copies ?? 1),
            0,
          );
          queueByShop.set(row.id, {
            queueCount: waiting,
            waitMinutes: Math.ceil((sheets * minPerPp) / online.length),
          });
        } catch {
          // Queue data is optional decoration — never fail the directory.
          queueByShop.set(row.id, { queueCount: 0, waitMinutes: null });
        }
      }),
    );

    return ok({
      locatedCount,
      shops: pageRows.map(({ row, distanceKm, status }) => {
        const queue = queueByShop.get(row.id) ?? { queueCount: 0, waitMinutes: null };
        return {
        id: row.id,
        name: row.name,
        slug: row.slug,
        image: row.logoUrl ?? null,
        address: row.fullAddress ?? row.address,
        latitude: row.latitude,
        longitude: row.longitude,
        distanceKm:
          distanceKm === null ? null : Math.round(distanceKm * 100) / 100,
        distanceLabel:
          distanceKm === null ? null : formatDistance(distanceKm),
        // No ratings/reviews exist in the DB — never invent them.
        rating: null,
        reviewCount: 0,
        openingHours: row.openingHours ?? null,
        openStatus: status.label,
        availableServices: parseServices(row.servicesJson),
        pricingSummary: parsePricing(row.pricingConfig),
        phone: maskPhone(row.phone),
        acceptingOrders: row.acceptingOrders ?? true,
        queueCount: queue.queueCount,
        waitMinutes: queue.waitMinutes,
        };
      }),
      pagination: {
        page,
        limit,
        total,
        totalPages,
        hasNext: page < totalPages,
        // True when the DB fetch hit FETCH_CAP: `total` may then be a
        // lower bound, not the full count.
        truncated,
      },
      query: {
        lat,
        lng,
        radiusKm: hasCoords ? radiusKm : null,
        search: search || null,
        openNow,
        service,
        sort,
      },
    });
  } catch (cause) {
    return fail(toAppError(cause));
  }
});
