import { db } from '@/lib/db';

/**
 * Sync repository — handles incremental pull + push operations.
 *
 * Implements Option A from docs/SYNC_PROTOCOL.md §3.4:
 *   - Every synced model has `revision Int` + `updatedAt DateTime`
 *   - Pull query: `WHERE shopId = ? AND updatedAt > ?cursor ORDER BY updatedAt LIMIT 100`
 *   - Conflict check: compare `baseRevision` (client's copy) vs `revision`
 *     (server's current) on push.
 *
 * Uses the Prisma client directly for delta queries — the BaseRepository
 * abstraction is per-table and doesn't give us the cross-entity fan-out we
 * need here.
 *
 * Schema notes: `Customer` and `DeviceSyncState` are new tables added in
 * Phase 5. The Prisma client is regenerated by the postinstall hook on every
 * install (and explicitly by `bun run db:generate`), so the typed accessors
 * `db.customer` and `db.deviceSyncState` are available. The runtime try/catch
 * around `customer.findMany` and the `getOrCreateSyncState` upsert guards
 * against the actual DB tables not existing yet — the schema may have been
 * pushed to the Prisma client types without `db:push` having run against the
 * live Postgres, so the queries throw P2021 (nonexistent table) at runtime.
 * In that case the pull skips Customers and the cursor falls back to an
 * in-memory default so the endpoint still responds cleanly.
 */

// Entities that participate in sync, with their table names.
export const SYNCED_ENTITIES = [
  'Shop',
  'Order',
  'PrintFile',
  'PrintJob',
  'PrintAgent',
  'Customer',
] as const;
export type SyncedEntity = (typeof SYNCED_ENTITIES)[number];

export interface SyncChange {
  entity: string;
  id: string;
  action: 'upsert' | 'delete';
  data: Record<string, unknown>;
  revision: number;
  updatedAt: string;
}

export interface PullResult {
  changes: SyncChange[];
  nextCursor: string;
  hasMore: boolean;
}

/**
 * Pull incremental changes since the cursor for a shop.
 *
 * Iterates each synced entity, queries rows with `updatedAt > cursor`,
 * and unifies them into a single time-ordered stream of changes. The
 * cursor advances to the latest `updatedAt` seen; `hasMore` is true when
 * we hit the per-entity limit (a coarse signal — clients should re-pull
 * immediately if true).
 */
export async function pullSince(
  shopId: string,
  cursor: string,
  limit = 100,
): Promise<PullResult> {
  const cursorDate = new Date(cursor);
  const changes: SyncChange[] = [];
  const prisma = db;

  // Pull Orders (server-authoritative — surface as upsert/delete to clients).
  const orders = await prisma.order.findMany({
    where: { shopId, updatedAt: { gt: cursorDate } },
    orderBy: { updatedAt: 'asc' },
    take: limit,
  });
  for (const o of orders) {
    changes.push({
      entity: 'Order',
      id: o.id,
      // `deletedAt` is null for live rows — soft-deleted rows surface as deletes.
      action: (o as any).deletedAt ? 'delete' : 'upsert',
      data: o as unknown as Record<string, unknown>,
      revision: (o as any).revision ?? 1,
      updatedAt: o.updatedAt.toISOString(),
    });
  }

  // Pull PrintFiles — these belong to a shop via their parent Order. The
  // current Prisma schema doesn't carry `shopId` on PrintFile (it's reached
  // through `orderId → Order.shopId`), so we filter via the relation.
  const files = await prisma.printFile.findMany({
    where: { order: { shopId }, updatedAt: { gt: cursorDate } },
    orderBy: { updatedAt: 'asc' },
    take: limit,
  });
  for (const f of files) {
    changes.push({
      entity: 'PrintFile',
      id: f.id,
      action: (f as any).deletedAt ? 'delete' : 'upsert',
      data: f as unknown as Record<string, unknown>,
      revision: (f as any).revision ?? 1,
      updatedAt: f.updatedAt.toISOString(),
    });
  }

  // Pull PrintJobs (shop-scoped, bidirectional — desktop reports status).
  const jobs = await prisma.printJob.findMany({
    where: { shopId, updatedAt: { gt: cursorDate } },
    orderBy: { updatedAt: 'asc' },
    take: limit,
  });
  for (const j of jobs) {
    changes.push({
      entity: 'PrintJob',
      id: j.id,
      action: (j as any).deletedAt ? 'delete' : 'upsert',
      data: j as unknown as Record<string, unknown>,
      revision: (j as any).revision ?? 1,
      updatedAt: j.updatedAt.toISOString(),
    });
  }

  // Pull the Shop itself (settings changes — server → desktop).
  const shop = await prisma.shop.findUnique({ where: { id: shopId } });
  if (shop && shop.updatedAt > cursorDate) {
    changes.push({
      entity: 'Shop',
      id: shop.id,
      action: (shop as any).deletedAt ? 'delete' : 'upsert',
      data: shop as unknown as Record<string, unknown>,
      revision: (shop as any).revision ?? 1,
      updatedAt: shop.updatedAt.toISOString(),
    });
  }

  // Pull PrintAgents for this shop (server → desktop — agent list).
  const agents = await prisma.printAgent.findMany({
    where: { shopId, updatedAt: { gt: cursorDate } },
    orderBy: { updatedAt: 'asc' },
    take: limit,
  });
  for (const a of agents) {
    changes.push({
      entity: 'PrintAgent',
      id: a.id,
      action: (a as any).deletedAt ? 'delete' : 'upsert',
      data: a as unknown as Record<string, unknown>,
      revision: (a as any).revision ?? 1,
      updatedAt: a.updatedAt.toISOString(),
    });
  }

  // Pull Customers (bidirectional — desktop can create customers offline).
  // Wrapped in try/catch: if the Customer table hasn't been migrated yet
  // (`db:push` not run), the query throws a P2021 (nonexistent table) — we
  // skip the entity rather than failing the whole pull.
  try {
    const customers = await prisma.customer.findMany({
      where: { shopId, updatedAt: { gt: cursorDate } },
      orderBy: { updatedAt: 'asc' },
      take: limit,
    });
    for (const c of customers) {
      changes.push({
        entity: 'Customer',
        id: c.id,
        action: c.deletedAt ? 'delete' : 'upsert',
        data: c as unknown as Record<string, unknown>,
        revision: c.revision ?? 1,
        updatedAt: c.updatedAt.toISOString(),
      });
    }
  } catch {
    /* Customer model may not exist yet if migration hasn't run */
  }

  // Sort all changes by updatedAt (asc) so the cursor advances monotonically.
  changes.sort((a, b) => a.updatedAt.localeCompare(b.updatedAt));

  // Determine the next cursor — the latest updatedAt in this batch, or the
  // original cursor if no changes were returned.
  const nextCursor =
    changes.length > 0 ? changes[changes.length - 1].updatedAt : cursor;
  // `hasMore` is a coarse signal: we set it true when ANY entity hit its
  // per-entity limit. The client should immediately re-pull with the
  // advanced cursor to drain the backlog.
  const hasMore =
    orders.length === limit ||
    files.length === limit ||
    jobs.length === limit ||
    agents.length === limit;

  // Truncate to the limit (after sorting, so the oldest `limit` changes are
  // returned first — the next pull picks up where this one left off).
  return { changes: changes.slice(0, limit), nextCursor, hasMore };
}

/**
 * Get or create a device sync state.
 *
 * Each (shopId, deviceId) pair has its own cursor. The deviceId is the
 * PrintAgent ID — the same daemon that polls print jobs is the one that
 * syncs. First-time registration creates a row with the epoch cursor so
 * the initial pull fetches everything.
 */
export async function getOrCreateSyncState(
  shopId: string,
  deviceId: string,
): Promise<{
  id: string;
  syncCursor: string;
  lastSyncAt: Date | null;
  lastPushAt: Date | null;
}> {
  const prisma = db;
  try {
    // `upsert` is the atomic get-or-create — avoids the race where two
    // concurrent device registrations both call `findUnique → create`.
    const state = await prisma.deviceSyncState.upsert({
      where: { shopId_deviceId: { shopId, deviceId } },
      update: {},
      create: { shopId, deviceId, syncCursor: '1970-01-01T00:00:00Z' },
    });
    return {
      id: state.id,
      syncCursor: state.syncCursor,
      lastSyncAt: state.lastSyncAt,
      lastPushAt: state.lastPushAt,
    };
  } catch {
    // If DeviceSyncState table doesn't exist (no db:push yet), return
    // in-memory defaults so the endpoint still responds. The cursor won't
    // persist across requests, but the API contract is honoured.
    return {
      id: crypto.randomUUID(),
      syncCursor: '1970-01-01T00:00:00Z',
      lastSyncAt: null,
      lastPushAt: null,
    };
  }
}

/**
 * Update the sync cursor after a successful pull.
 *
 * Only advances the cursor forward — never backward. The caller is expected
 * to pass the `nextCursor` from `pullSince`, which is already monotonically
 * greater than the previous cursor (or equal, if no new changes).
 */
export async function updateSyncCursor(
  stateId: string,
  cursor: string,
): Promise<void> {
  const prisma = db;
  try {
    await prisma.deviceSyncState.update({
      where: { id: stateId },
      data: { syncCursor: cursor, lastSyncAt: new Date() },
    });
  } catch {
    /* table may not exist — best-effort */
  }
}

/**
 * Mark a push timestamp on the device's sync state.
 */
export async function markPushAt(stateId: string): Promise<void> {
  const prisma = db;
  try {
    await prisma.deviceSyncState.update({
      where: { id: stateId },
      data: { lastPushAt: new Date() },
    });
  } catch {
    /* best-effort */
  }
}
